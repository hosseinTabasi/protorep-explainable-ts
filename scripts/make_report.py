"""Render reports/RESULTS.md from experiments/results/*.csv (no hand-typed numbers)."""
import os
import pandas as pd
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "experiments", "results")


def md(df, nd=4):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{nd}f}")
    return df.to_markdown(index=False)


out = ["# ProtoRep results (generated by scripts/make_report.py; mean/std over seeds 0,1,2)\n"]
for title, f in [("E1 Detection vs baselines", "e1_detection_summary.csv"),
                 ("E2 Attribution faithfulness (deletion AUC lower = better, insertion AUC higher = better)", "e2_faithfulness_summary.csv"),
                 ("E3 Prototype / cluster purity vs TEP fault id (22 classes)", "e3_purity_summary.csv"),
                 ("E4 Label efficiency, linear probe on TEP test runs (macro-F1)", "e4_label_efficiency_summary.csv"),
                 ("E4b Weak supervision (train: normal refs + 10% labelled windows of SKAB 'other'; test: valve1+valve2)", "e4b_weak_summary.csv"),
                 ("E5 Ablations (SKAB)", "e5_ablation_summary.csv")]:
    p = os.path.join(R, f)
    if os.path.exists(p):
        out += [f"## {title}\n", md(pd.read_csv(p)), "\n"]
open(os.path.join(ROOT, "reports", "RESULTS.md"), "w").write("\n".join(out))
print("\n".join(out))
